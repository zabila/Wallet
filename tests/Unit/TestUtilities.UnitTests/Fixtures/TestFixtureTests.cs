    }

    [Fact]
    public void Create_ShouldWorkWithDateTime()
    {
        // Arrange
        var testFixture = new TestableTestFixture();

        // Act
        var result = testFixture.Create<DateTime>();

        // Assert
        result.Should().NotBe(default);
    }

    [Fact]
    public void CreateMany_ShouldWorkWithValueTypes()
    {
        // Arrange
        var testFixture = new TestableTestFixture();

        // Act
        var results = testFixture.CreateMany<int>(5);

        // Assert
        results.Should().HaveCount(5);
        results.Should().OnlyHaveUniqueItems();
        results.Should().NotContain(0);
    }

    [Fact]
    public void CustomAutoDataAttribute_ShouldCreateInstance()
    {
        // Act
        var attribute = new CustomAutoDataAttribute();

        // Assert
        attribute.Should().NotBeNull();
        attribute.Should().BeAssignableTo<AutoFixture.Xunit2.AutoDataAttribute>();
    }

    private sealed class CustomTestFixture : TestFixture
    {
        public bool ConfigureCalled { get; private set; }

        protected override void ConfigureFixture()
        {
            base.ConfigureFixture();
            ConfigureCalled = true;

            // Example custom configuration
            Fixture.Customize<TestClass>(composer =>
                composer.With(x => x.Name, "CustomName"));
        }

        // Expose protected methods for testing
        public new T Create<T>() => base.Create<T>();
    }

    [Fact]
    public void ConfigureFixture_ShouldBeCalledInConstructor()
    {
        // Act
        var testFixture = new CustomTestFixture();

        // Assert
        testFixture.ConfigureCalled.Should().BeTrue();
    }

    [Fact]
    public void ConfigureFixture_ShouldAllowCustomization()
    {
        // Arrange
        var testFixture = new CustomTestFixture();

        // Act
        var result = testFixture.Create<TestClass>();

        // Assert
        result.Name.Should().Be("CustomName");
    }
}
